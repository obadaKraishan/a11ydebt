"""Bundle the a11ydebt modules and job.py into one Kaggle script kernel.

    cd kaggle/androidcontrol_parse && uv run python build_kernel.py config_run1.json

This writes ``kaggle/androidcontrol_parse/build/<name>/run.py`` and ``kernel-metadata.json``. Push
the build with ``kaggle kernels push -p kaggle/androidcontrol_parse/build/<name>``.

``run.py`` carries base64 copies of the modules it needs (stdlib-only a11ydebt code plus job.py),
the embedded config, the git commit it was built from, and a pinned pyarrow version. pyarrow is
installed into a private folder when the image's version differs, before it is first imported.
For local tests, these environment variables override the defaults: A11YDEBT_CONFIG,
A11YDEBT_OUT, A11YDEBT_WORK, A11YDEBT_SRC and A11YDEBT_SKIP_PIP.
"""

from __future__ import annotations

import argparse
import base64
import importlib.metadata
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "src" / "a11ydebt"
MODULES = ("__init__.py", "taxonomy.py", "tfrecord.py", "counts.py", "androidcontrol.py")
KAGGLE_USER = "obadakraishan"

RUN_TEMPLATE = '''\
# a11ydebt AndroidControl parse kernel, generated by kaggle/androidcontrol_parse/build_kernel.py.
# Do not edit: rebuild it from the a11ydebt repo. Build info is in BUILD below.
import base64
import importlib.metadata
import json
import os
import subprocess
import sys
from pathlib import Path

BUILD = __BUILD__
CONFIG = __CONFIG__
PINNED = __PINNED__
SOURCES = __SOURCES__


def pin_packages():
    """Make the pinned pyarrow importable before anything imports pyarrow."""
    if os.environ.get("A11YDEBT_SKIP_PIP"):
        return "skipped"
    try:
        if importlib.metadata.version("pyarrow") == PINNED["pyarrow"]:
            return "preinstalled"
    except importlib.metadata.PackageNotFoundError:
        pass
    target = Path(os.environ.get("A11YDEBT_PKGS", "/tmp/a11ydebt_pkgs"))
    subprocess.run(
        [sys.executable, "-m", "pip", "install", "--quiet", "--no-deps", "--target", str(target),
         "pyarrow==" + PINNED["pyarrow"]],
        check=True,
    )
    sys.path.insert(0, str(target))
    return "installed"


def materialize():
    root = Path(os.environ.get("A11YDEBT_SRC", "/tmp/a11ydebt_src"))
    for rel, payload in SOURCES.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(base64.b64decode(payload))
    sys.path.insert(0, str(root))


if __name__ == "__main__":
    pin = pin_packages()
    materialize()
    import a11ydebt_job

    config = CONFIG
    if os.environ.get("A11YDEBT_CONFIG"):
        config = json.loads(Path(os.environ["A11YDEBT_CONFIG"]).read_text(encoding="utf-8"))
    sys.exit(a11ydebt_job.main([], config=config, build=dict(BUILD, pyarrow_pin=pin)))
'''


def git_commit() -> str:
    def git(*args: str) -> str:
        return subprocess.run(
            ["git", "-C", str(HERE), *args], capture_output=True, text=True, check=False
        ).stdout

    commit = git("rev-parse", "--short", "HEAD").strip() or "unknown"
    dirty = bool(git("status", "--porcelain", "--", "src", "kaggle").strip())
    return commit + ("+dirty" if dirty else "")


def build(config_path: Path, out_root: Path | None = None) -> Path:
    config = json.loads(Path(config_path).read_text(encoding="utf-8"))
    files = {f"a11ydebt/{m}": (SRC / m).read_bytes() for m in MODULES}
    files["a11ydebt_job.py"] = (HERE / "job.py").read_bytes()
    pinned = {"pyarrow": importlib.metadata.version("pyarrow")}
    build_info = {
        "a11ydebt_commit": git_commit(),
        "built_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "config": config["name"],
        "modules": sorted(files),
    }
    run_py = (
        RUN_TEMPLATE.replace("__BUILD__", repr(build_info))
        .replace("__CONFIG__", repr(config))
        .replace("__PINNED__", repr(pinned))
        .replace("__SOURCES__", repr({k: base64.b64encode(v).decode() for k, v in files.items()}))
    )
    metadata = {
        "id": config.get("kernel_id") or f"{KAGGLE_USER}/a11ydebt-androidcontrol-{config['name']}",
        "title": config.get("kernel_title") or f"a11ydebt androidcontrol {config['name']}",
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": False,
        "enable_tpu": False,
        "enable_internet": True,
        "machine_shape": "",  # Kaggle has no named CPU shape: no GPU/TPU and an empty shape = CPU
        "docker_image_pinning_type": "original",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    out_dir = (out_root or HERE / "build") / config["name"]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "run.py").write_text(run_py, encoding="utf-8")
    (out_dir / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
    )
    return out_dir


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("config", type=Path)
    parser.add_argument("--out-root", type=Path, default=None)
    args = parser.parse_args(argv)
    out_dir = build(args.config, args.out_root)
    print(f"built {out_dir}/run.py and kernel-metadata.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
